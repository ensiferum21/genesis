#!/usr/bin/env python3
"""B20_R93: run the adaptation cell over the evidence.

    python3 scripts/b20r93_cell.py ROOT OUT [--today YYYY-MM-DD] [--budget SECONDS] [--include-unfinished]
    python3 scripts/b20r93_cell.py ROOT OUT --check DESIGN.json [--today YYYY-MM-DD]

ROOT is a Genesis tree (its `evidence/` is read, nothing in it is changed); OUT receives:
  caveats.json      every study's caveats, as the receptors sensed them
  ledger.json       the lineages, attempts, outcomes, response memory and the cell's account of what it inferred
  cost_model.json   the cost model fitted to the earlier studies' run logs, with its residuals
  capabilities.json what the code and the evidence show the system can do
  next_design.json  the design the cell proposes for the next study
  plan.json         why: the response chosen per caveat, what was skipped or deferred, marginal costs, work orders
  checkpoint.json   the checkpoint run on the proposal (and, with --check, on DESIGN.json instead)
  CAVEATS.md        all of it for a human reader
With --check, the exit status is 0 if DESIGN.json passes the checkpoint and 1 if it does not.
"""
import argparse
import datetime
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'src'))

from genesis.adaptation import capabilities, metabolism                      # noqa: E402
from genesis.adaptation.checkpoint import check                             # noqa: E402
from genesis.adaptation.design import compose, vbs_contributors             # noqa: E402
from genesis.adaptation.discovery import discover                           # noqa: E402
from genesis.adaptation.ledger import rebuild                               # noqa: E402
from genesis.adaptation.receptors import CAVEAT_TYPES, stale_knowledge      # noqa: E402

CATALOG = Path(__file__).resolve().parents[1] / 'src/genesis/adaptation/baselines.json'


def _dump(path, obj):
    Path(path).write_text(json.dumps(obj, indent=1, sort_keys=True, default=str) + '\n')


def report(today, profiles, led, seen, model, resid, caps, design, plan, chk):
    L = ['# Caveats: what the adaptation cell sees', '',
         f'Generated by `scripts/b20r93_cell.py` on {today} from the evidence alone: '
         f'{len(profiles)} time-to-solution studies were discovered ({", ".join(p.study for p in profiles)}). '
         'Nothing here was registered, labelled or declared by hand.', '',
         '## Open weaknesses', '', '| Lineage | Status | Severity | Last seen | Attempts |', '|---|---|---|---|---|']
    for k, e in led.open().items():
        att = '; '.join(f"{a['study']} {a['response']} (dose {a['dose']}): {a['outcome']}" for a in e['attempts'])
        L.append(f"| {k} | {e['status']} | {e['severity']} | {e['study']} | {att or 'none'} |")
    closed = {t: lin for t, lin in led.lineages.items() if lin['status'] in ('RESOLVED', 'CLEARED')}
    L += ['', '## Closed', '', '| Lineage | Status | By |', '|---|---|---|']
    for t, lin in closed.items():
        L.append(f"| {t}@{lin['first_seen']} | {lin['status']} | {lin.get('resolved_by') or 'no response credited'} |")
    L += ['', '## What the cell inferred, in order', ''] + [f'- {e}' for e in led.events]
    L += ['', '## Response memory', '',
          '| Response | Resolved | Improving | Persistent | Underdosed | Relapsed | Score |',
          '|---|---|---|---|---|---|---|']
    for r, o in sorted(led.outcomes.items()):
        L.append(f"| {r} | {o['RESOLVED']} | {o['IMPROVING']} | {o['PERSISTENT']} | {o['UNDERDOSED']} | "
                 f"{o['RELAPSED']} | {led.score(r):.2f} |")
    L += ['', '## Its own costs', '',
          f"Overhead per run fitted to its own run logs: {model['overhead_s']} s (median over "
          f"{len([v for v in model['fitted_on'].values() if v.get('overhead_s')])} studies).", '',
          '| Study | Observed wall s | Predicted s |', '|---|---|---|']
    for k, v in resid.items():
        L.append(f"| {k} | {v['observed_s']} | {v['predicted_s']} |")
    L += ['', '## The next study it proposes', '', '```json', json.dumps(design, indent=1, sort_keys=True), '```', '',
          '| Caveat | Response |', '|---|---|']
    for k, r in plan['chosen'].items():
        L.append(f'| {k} | {r} |')
    for k, r in plan['deferred'].items():
        L.append(f'| {k} | deferred: {r} |')
    for k, r in plan['escalate'].items():
        L.append(f'| {k} | escalate: {r} |')
    L += ['', f"Estimated cost {plan['estimated_runtime_s']} s against a limit of {plan['limit_s']} s"
          + (f" ({plan['over_budget']})" if plan.get('over_budget') else '') + '.', '',
          'Marginal cost per adaptation (s): ' + ', '.join(f'{k} {v}' for k, v in plan['marginal_cost_s'].items()), '',
          '### Work orders (what the system must be able to do before this study can run)', '']
    L += [f"- **{w['need']}**: {w['what']}" for w in plan.get('work_orders', [])] or ['- none']
    L += ['', '## Checkpoint on the proposal', '', f"pass: {chk['pass']}; addressed {len(chk['addressed'])}, "
          f"unaddressed {len(chk['unaddressed'])}, deferred {len(chk['deferred'])}, "
          f"membrane {chk['membrane'] or 'clean'}",
          '', '## Caveat types', ''] + [f'- **{t}**: {m}' for t, m in CAVEAT_TYPES.items()]
    return '\n'.join(L) + '\n'


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('root')
    ap.add_argument('out')
    ap.add_argument('--today', default=datetime.date.today().isoformat())
    ap.add_argument('--budget', type=float, default=None)
    ap.add_argument('--include-unfinished', action='store_true')
    ap.add_argument('--check', default=None)
    a = ap.parse_args(argv)
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    catalog = json.loads(CATALOG.read_text())
    profiles = discover(a.root, include_unfinished=a.include_unfinished)
    if not profiles:
        print('no time-to-solution studies found', file=sys.stderr)
        return 2
    led, seen, studies = rebuild(profiles, a.root, catalog)
    model = metabolism.fit(studies)
    resid = metabolism.residuals(studies, model)
    caps = capabilities.scan([v['design'] for v in seen.values()])
    base = seen[profiles[-1].study]['design']
    design, plan = compose(led, base, catalog, model, budget_s=a.budget, contributors=vbs_contributors(studies[-1]),
                           caps=caps, today=a.today)
    target = json.loads(Path(a.check).read_text()) if a.check else design
    chk = check(target, led, catalog=catalog, today=a.today)
    _dump(out / 'caveats.json', {s: [c.record() for c in v['caveats']] for s, v in seen.items()})
    led.save(out / 'ledger.json')
    _dump(out / 'cost_model.json', {'model': model, 'residuals': resid})
    _dump(out / 'capabilities.json', caps)
    _dump(out / 'next_design.json', design)
    _dump(out / 'plan.json', plan)
    _dump(out / 'checkpoint.json', dict(chk, checked=a.check or 'next_design.json', today=a.today,
                                        stale=[c.record() for c in stale_knowledge(catalog, a.today)]))
    (out / 'CAVEATS.md').write_text(report(a.today, profiles, led, seen, model, resid, caps, design, plan, chk))
    print(f"{len(profiles)} studies; {len(led.open())} open lineages; proposal {design['estimated_runtime_s']} s; "
          f"checkpoint {'PASS' if chk['pass'] else 'FAIL'}")
    if a.check:
        return 0 if chk['pass'] else 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
