#!/usr/bin/env python3
"""B20_R23: E1b readiness (DEV). An LP-ordered greedy pipeline through the custodian's runner.

    b20r23_e1b_readiness.py OUT_DIR            run (resumable: rows already on disk are kept) and summarise
    b20r23_e1b_readiness.py OUT_DIR --summary  summarise existing rows only

Why. E1 (represent-and-repair, cross_2) cannot be powered at its decided design on the e1-hard-v1
family (B20R12-OPEN-1). B20_RX3 and its fresh-seed replication RX3b found a capability gain of
LP-ordered greedy with LP-perturbed restarts (``lp_greedy``; builder-written,
``discovery/construct.py``) at 2.0 CPU s on families with room to the certified optimum (B20_R14).
B20_R23 made such pipelines a candidate kind (``construct-pipeline-v1``) that the custodian's runner
executes in the OCI sandbox. This pilot asks whether a second better-solver claim, "E1b", would be
ready for review under E1's decided design: time-matched conventional baselines, a custodian-selected
comparator, the centred power model with at least 10 tasks per stratum, and the B19 DRAFT plan.

Everything below is fixed before running.

Settings (builder-chosen from B20_R14 and RX3; a study family would need a reviewer decision):
  C1 triangle_free_host_v1 erdos n30 p0.3     C2 triangle_free_host_v1 erdos n40 p0.2
  C3 c4_host_v2 erdos n30 p0.2
  12 fresh DEV hosts per setting, generator seed 20262401 + 10 i (i = 0, 1, 2), each excluding the
  exposure identities of: every graph host recorded in any JSON or JSONL file under evidence/ and
  handoff/ (both domains; empty files are listed and skipped), the E1 exposure set regenerated by
  b20r12_e1_redo.exposure, and the hosts of the earlier settings of this pilot.

Arms, all through candidates.run(isolation='runc') under one resource profile
{cpu 4 s, 2048 MiB, wall 20 s, 1000 queries}; per-host seed digest({'pilot': 'b20r23', 'task': id})[:12]:
  candidate    construct-pipeline-v1 {init lp_greedy, frac 1.0, finish none, cpu_seconds 2.0, seed 0}
  baselines    the three fixed DSL programs as dsl-time-matched-v1, 2.0 CPU s of restarts each
  diagnostic   triangle-free only: represent-and-repair-v1 cross_2 with 2.0 CPU s (E1's candidate at
               this budget). Reported, never a comparator.
A failed run scores 0 (the plan's failure rule).

Reference optimum: discovery.obstruction.certify, seeded with the best witness among the arms,
120 s per host. A host has an optimum only if lower == upper. Hosts without one are reported and not
scored. A domain is scored only if each of its strata has at least 9 of 12 hosts certified (B20_R14's
75% rule); otherwise its verdict is UNSETTLED_REFERENCE.

Comparator for the pilot: the strongest time-matched baseline by total value over the domain's pilot
hosts (the custodian's SELECT rule, applied to the pilot).

Analysis per domain: the B19 DRAFT plan core, unchanged (minimum useful effect 0.5, design effect 1.0,
alpha 0.05, Holm over 3, strata = family setting, max cost ratio 3.0). The one exception is the
multiplicity family_id, which names the domain. The analysis is a dry run (kernel.analysis.analyze).
Power: power.required_sample(rows, plan, sims=1000, min_tasks_per_stratum=10, headroom='centred').

Verdict per domain (mean = mean paired difference over scored hosts, strata pooled, as in B20_R11/R12;
the plan's own estimand is reported beside it):
  UNSETTLED_REFERENCE  a stratum has fewer than 9 certified hosts
  EFFECT_BELOW_MUE     mean < 0.5
  COST_RULE_FAILS      cgroup CPU ratio candidate / comparator > 3.0
  UNDERPOWERED         the centred power model chooses no size in its grid
  READY_FOR_REVIEW     otherwise

A DEV readiness diagnostic: it licenses no claim. READY_FOR_REVIEW only means a GV3 package "E1b" can
be drafted. Its host family would still need a decision, because e1-hard-v1 applies to E1 only (the
user's decision, 13 Oct 2026), and the candidate is a builder-written method.
"""
import json
from pathlib import Path
import statistics
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))
sys.path.insert(0, str(ROOT / 'scripts'))

from genesis import calibration as CAL  # noqa: E402
from genesis import candidates as C  # noqa: E402
from genesis.common import canonical, code_identity, digest  # noqa: E402
from genesis.domains import ADAPTERS, Unsupported  # noqa: E402
from genesis.dsl import baseline_programs  # noqa: E402
from genesis.kernel.analysis import analyze  # noqa: E402
from genesis.models import GraphTask  # noqa: E402
from genesis.power import approximation_check, required_sample  # noqa: E402

import b20r11_e1_readiness as R11  # noqa: E402
import b20r12_e1_redo as R12  # noqa: E402

TF, C4 = 'triangle_free_host_v1', 'c4_host_v2'
SETTINGS = [('C1', TF, 'erdos', {'n': 30, 'p': 0.3}),
            ('C2', TF, 'erdos', {'n': 40, 'p': 0.2}),
            ('C3', C4, 'erdos', {'n': 30, 'p': 0.2})]
HOSTS, SEED_BASE = 12, 20262401
PROFILE = {'cpu_seconds': 4, 'memory_mib': 2048, 'wall_seconds': 20, 'queries': 1000}
SEARCH_S = 2.0
CERTIFY_S = 120
MIN_CERTIFIED = 9
CANDIDATE = {'init': 'lp_greedy', 'frac': 1.0, 'finish': 'none', 'cpu_seconds': SEARCH_S, 'seed': 0}


def arms(domain):
    out = {'candidate': C.build_descriptor('construct-pipeline-v1', domain, CANDIDATE, **PROFILE)}
    for n, p in sorted(baseline_programs().items()):
        out[f'{n}_tm'] = C.build_descriptor('dsl-time-matched-v1', domain, {'program': p.model_dump(mode='json'),
                                                                            'cpu_seconds': SEARCH_S}, **PROFILE)
    if domain == TF:
        out['cross_2_diag'] = C.build_descriptor('represent-and-repair-v1', domain,
                                                 {'representation': 'cross_2', 'cpu_seconds': SEARCH_S, 'seed': 0},
                                                 **PROFILE)
    return out


# ------------------------------------------------------------------ exposure

def _walk(o, acc):
    if isinstance(o, dict):
        if {'task_id', 'domain', 'n', 'edges'} <= set(o):
            acc.append(o)
            return
        for v in o.values():
            _walk(v, acc)
    elif isinstance(o, list):
        for v in o:
            _walk(v, acc)


def named_hosts():
    """Every graph host recorded under evidence/ and handoff/, as tasks (both domains)."""
    acc, empty = [], []
    files = sorted([*(ROOT / 'evidence').rglob('*.json'), *(ROOT / 'evidence').rglob('*.jsonl'),
                    *(ROOT / 'handoff').rglob('*.json')])
    for f in files:
        text = f.read_text()
        if not text.strip():
            empty.append(str(f.relative_to(ROOT)))
            continue
        if f.suffix == '.json':
            _walk(json.loads(text), acc)
        else:
            for line in text.splitlines():
                if line.strip():
                    _walk(json.loads(line), acc)
    out = {}
    for t in acc:
        if t['domain'] in (TF, C4):
            g = GraphTask.model_validate_json(canonical(t))
            out[(g.domain, g.task_id, digest(g.model_dump(mode='json')))] = g
    return list(out.values()), {'files_scanned': len(files), 'empty_files_skipped': empty,
                                'host_records': len(acc), 'distinct_hosts': len(out)}


def identities(tasks):
    out = set()
    for t in tasks:
        ident = ADAPTERS[t.domain].exposure_identity(t)
        if isinstance(ident, Unsupported):
            raise RuntimeError(f'{t.task_id}: exposure identity unsupported; cannot screen against it')
        out.add(ident['canonical'])
    return out


def hosts(log):
    named, scan = named_hosts()
    e1_excluded, e1_named = R12.exposure(CAL.load(TF, ROOT, study='e1'))
    excluded = identities(named) | set(e1_excluded)
    scan.update(e1_named_hosts=len(e1_named), excluded_identities=len(excluded))
    log(f'exposure: {scan["distinct_hosts"]} hosts named in {scan["files_scanned"]} files, '
        f'{len(e1_named)} E1 hosts regenerated; {len(excluded)} identities excluded')
    out = {}
    for i, (sid, domain, family, params) in enumerate(SETTINGS):
        tasks, seen, gen = ADAPTERS[domain].generate(SEED_BASE + 10 * i, HOSTS, 'DEV', family, params,
                                                     excluded=excluded)
        if identities(tasks) & excluded:
            raise RuntimeError('a generated host collides with a named host')
        excluded = set(seen)
        out[sid] = {'domain': domain, 'family': family, 'params': params, 'seed': SEED_BASE + 10 * i,
                    'generator': gen, 'tasks': tasks}
    return out, scan


# ------------------------------------------------------------------ run

def run_host(task, all_arms):
    seed = int(digest({'pilot': 'b20r23', 'task': task.task_id})[:12], 16)
    res, best = {}, None
    for name, desc in all_arms.items():
        r = C.run(task, desc, seed=seed, expected_id=desc['descriptor_id'], isolation='runc')
        ok = r['status'] == 'SUCCESS'
        res[name] = {'value': r['result']['value'] if ok else 0, 'run': 'SUCCESS' if ok else 'FAILED',
                     'status': r['status'], 'cpu_ns': r['cpu_ns'] if type(r.get('cpu_ns')) is int else 0,
                     'meter': r.get('meter'), 'isolation': r.get('isolation')}
        if ok and (best is None or r['result']['value'] > best[0]):
            best = (r['result']['value'], [tuple(e) for e in r['result']['selected']], name)
    from genesis.discovery import obstruction as O
    rec = O.certify(task, best[1], seconds=CERTIFY_S)
    cert = {'seeded_from': best[2], 'seed_value': best[0], 'lower': rec['lower'], 'upper': rec['upper'],
            'upper_method': rec['upper_evidence']['method'], 'status': rec['status'], 'wall_s': rec['wall_s']}
    return {'task_id': task.task_id, 'stratum': task.family, 'split': task.split, 'arms': res, 'certify': cert,
            'optimum': rec['lower'] if rec['lower'] == rec['upper'] else None}


def run(out, H, log):
    rows_path = out / 'rows.jsonl'
    done = set()
    if rows_path.exists():
        done = {json.loads(line)['task_id'] for line in rows_path.read_text().splitlines() if line.strip()}
    t0 = time.monotonic()
    with rows_path.open('a') as fh:
        for sid, s in H.items():
            all_arms = arms(s['domain'])
            for t in s['tasks']:
                if t.task_id in done:
                    continue
                r = dict(run_host(t, all_arms), setting=sid, domain=s['domain'])
                fh.write(json.dumps(r, sort_keys=True) + '\n')
                fh.flush()
                log(f'{sid} {t.task_id}: opt {r["optimum"]} (L{r["certify"]["lower"]}/U{r["certify"]["upper"]} '
                    f'{r["certify"]["wall_s"]:.0f}s) ' + ', '.join(f'{n} {a["value"]}' for n, a in r['arms'].items())
                    + f' [{time.monotonic() - t0:.0f}s]')


# ------------------------------------------------------------------ analysis

def analyse_domain(domain, H, rows):
    sids = [sid for sid, s in H.items() if s['domain'] == domain]
    drows = [r for r in rows if r['setting'] in sids]
    names = list(arms(domain))
    tm = [n for n in names if n.endswith('_tm')]
    totals = {n: sum(r['arms'][n]['value'] for r in drows) for n in names}
    comparator = max(tm, key=lambda n: (totals[n], n))
    certified = {sid: sum(r['optimum'] is not None for r in drows if r['setting'] == sid) for sid in sids}
    scored = [r for r in drows if r['optimum'] is not None]
    cpu = {n: sum(r['arms'][n]['cpu_ns'] for r in drows) for n in names}
    ratio = cpu['candidate'] / cpu[comparator] if cpu[comparator] else None
    plan = dict(R11.draft_record()['analysis_plan_core'], decision_record_sha256='0' * 64)
    plan['multiplicity'] = dict(plan['multiplicity'], family_id=f'sealed_evaluation:{domain}')
    mue, max_ratio = plan['minimum_useful_effect'], plan['cost']['max_ratio']
    out = {'settings': {sid: {k: H[sid][k] for k in ('family', 'params', 'seed')} for sid in sids},
           'hosts': len(drows), 'certified_by_setting': certified, 'scored': len(scored),
           'comparator': comparator, 'totals': totals, 'cpu_ns_by_arm': cpu,
           'cpu_ratio_candidate_to_comparator': round(ratio, 4) if ratio else None,
           'failures': {n: sum(r['arms'][n]['run'] == 'FAILED' for r in drows) for n in names},
           'plan_minimum_useful_effect': mue, 'plan_max_cost_ratio': max_ratio}
    if min(certified.values()) < MIN_CERTIFIED:
        out['verdict'] = 'UNSETTLED_REFERENCE'
        return out, None, None
    prow = [{'task_id': r['task_id'], 'stratum': r['stratum'], 'status': 'SCORED', 'split': r['split'],
             'optimum': r['optimum'],
             'candidate': {k: r['arms']['candidate'][k] for k in ('value', 'run', 'cpu_ns')},
             'baseline': {k: r['arms'][comparator][k] for k in ('value', 'run', 'cpu_ns')}} for r in scored]
    result = analyze(prow, plan)
    power = required_sample(prow, plan, sims=1000, min_tasks_per_stratum=10, headroom='centred')
    chosen = (power.get('chosen') or {}).get('tasks_per_stratum')
    agreement = approximation_check(prow, plan, chosen, sims=40, headroom='centred') if chosen else None
    diffs = [r['candidate']['value'] - r['baseline']['value'] for r in prow]
    mean = statistics.fmean(diffs)
    if mean < mue:
        verdict = 'EFFECT_BELOW_MUE'
    elif ratio is None or ratio > max_ratio:
        verdict = 'COST_RULE_FAILS'
    elif not chosen:
        verdict = 'UNDERPOWERED'
    else:
        verdict = 'READY_FOR_REVIEW'
    strata = {}
    for r in prow:
        strata.setdefault(r['stratum'], []).append(r['candidate']['value'] - r['baseline']['value'])
    gaps = {n: round(statistics.fmean(r['optimum'] - r['arms'][n]['value'] for r in scored), 4) for n in names}
    out.update({
        'mean_difference': round(mean, 4),
        'stratum_mean_differences': {s: round(statistics.fmean(v), 4) for s, v in sorted(strata.items())},
        'stratum_tasks': {s: len(v) for s, v in sorted(strata.items())},
        'wins_ties_losses': [sum(d > 0 for d in diffs), sum(d == 0 for d in diffs), sum(d < 0 for d in diffs)],
        'optimum_hits': {n: sum(r['arms'][n]['value'] == r['optimum'] for r in scored) for n in names},
        'mean_gap_to_optimum': gaps,
        'draft_plan_dry_run': {k: result.get(k) for k in ('decision', 'estimate', 'interval', 'p_value', 'checks',
                                                           'cost_ratio')},
        'power_centred': {k: power.get(k) for k in ('status', 'chosen', 'power_at_minimum_useful_effect',
                                                     'false_positive_rate_at_zero_effect', 'pilot_strata', 'table')},
        'approximation_agreement': agreement, 'verdict': verdict})
    if domain == TF:
        d2 = [r['arms']['candidate']['value'] - r['arms']['cross_2_diag']['value'] for r in scored]
        out['diagnostic_candidate_minus_cross_2'] = {'mean': round(statistics.fmean(d2), 4),
                                                     'wins_ties_losses': [sum(d > 0 for d in d2), sum(d == 0 for d in d2),
                                                                          sum(d < 0 for d in d2)]}
    return out, prow, power


def analyse(out, H, scan):
    rows = [json.loads(line) for line in (out / 'rows.jsonl').read_text().splitlines() if line.strip()]
    want = {t.task_id for s in H.values() for t in s['tasks']}
    if {r['task_id'] for r in rows} != want:
        raise RuntimeError(f'{len(want - {r["task_id"] for r in rows})} hosts not yet run')
    summary = {'schema': 'genesis-b20r23-e1b-readiness-v1', 'domains': {}, 'exposure_scan': scan,
               'profile': PROFILE, 'search_seconds': SEARCH_S, 'certify_seconds': CERTIFY_S,
               'min_certified_per_stratum': MIN_CERTIFIED, 'candidate_parameters': CANDIDATE,
               'descriptors': {d: {n: a['descriptor_id'] for n, a in arms(d).items()} for d in (TF, C4)},
               'status': 'DEV readiness diagnostic; no sealed task; licenses no claim'}
    for domain in (TF, C4):
        s, prow, power = analyse_domain(domain, H, rows)
        summary['domains'][domain] = s
        if prow is not None:
            R11.dump(out / f'pilot_rows_{domain}.json', prow)
            R11.dump(out / f'power_analysis_centred_{domain}.json', power)
    summary['verdicts'] = {d: s['verdict'] for d, s in summary['domains'].items()}
    summary['code_identity'] = code_identity(ROOT)['sha256']
    R11.dump(out / 'summary.json', summary)
    return summary


def main(argv=None):
    argv = argv or sys.argv[1:]
    out = Path(argv[0])
    out.mkdir(parents=True, exist_ok=True)
    logf = (out / 'run.log').open('a')
    t0 = time.monotonic()

    def log(msg):
        line = f'[{time.monotonic() - t0:7.1f}s] {msg}'
        print(line, flush=True)
        logf.write(line + '\n')
        logf.flush()
    H, scan = hosts(log)
    R11.dump(out / 'hosts.json', {sid: dict({k: v for k, v in s.items() if k != 'tasks'},
                                            tasks=[t.model_dump(mode='json') for t in s['tasks']])
                                  for sid, s in H.items()})
    if '--summary' not in argv:
        run(out, H, log)
    s = analyse(out, H, scan)
    for d, x in s['domains'].items():
        log(f'{d}: {x["verdict"]}; comparator {x["comparator"]}; certified {x["certified_by_setting"]}; '
            f'mean {x.get("mean_difference")}; strata {x.get("stratum_mean_differences")}; '
            f'cpu ratio {x["cpu_ratio_candidate_to_comparator"]}; power {(x.get("power_centred") or {}).get("status")} '
            f'{(x.get("power_centred") or {}).get("chosen")}; dry run {(x.get("draft_plan_dry_run") or {}).get("decision")}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
