def registry():
    from .macros import IMPLEMENTED
    out = []
    for name, ops in ENGINES:
        if name in IMPLEMENTED:
            status, note = 'IMPLEMENTED_BOUNDED', 'macros.' + IMPLEMENTED[name][0].__name__
        elif name in INFRASTRUCTURE:
            status, note = 'INFRASTRUCTURE_BOUNDED', INFRASTRUCTURE[name]
        else:
            status, note = 'EXPRESSIBLE_NOT_INSTANTIATED', 'composition hypothesis only'
        out.append({'engine': name, 'composition': list(ops), 'status': status, 'note': note})
    return out


def summary():
    from collections import Counter
    return dict(Counter(r['status'] for r in registry()))
