_TERM_CACHE = {}


def _buckets(system, max_term):
    key = (system, max_term)
    if key not in _TERM_CACHE:
        spec = SYSTEMS[system]
        by = terms(spec['ops'], max_term)
        buckets = {}
        for k, ts in by.items():
            for t in ts:
                buckets.setdefault(fingerprint(t, spec['decider']), []).append(t)
        _TERM_CACHE[key] = {fp: v for fp, v in buckets.items() if len(v) > 1}
    return _TERM_CACHE[key]


def sample_targets(system, count, *, min_total, max_total, max_term=5, seed=0, exclude=()):
    """Random true equations with min_total ≤ nodes ≤ max_total, distinct up to renaming
    and orientation, avoiding `exclude`."""
    rng = random.Random(seed)
    buckets = _buckets(system, max_term)
    keys = sorted(buckets, key=repr)
    seen = {canon(e) for e in exclude}
    out, tries = [], 0
    while len(out) < count and tries < count * 2000:
        tries += 1
        b = buckets[keys[rng.randrange(len(keys))]]
        a, c = rng.choice(b), rng.choice(b)
        n = size(a) + size(c)
        if a == c or not (min_total <= n <= max_total) or (a[0] == 'var' and c[0] == 'var'):
            continue
        e = canon((a, c))
        if e in seen or e[0] == e[1]:
            continue
        seen.add(e); out.append(e)
    return out
