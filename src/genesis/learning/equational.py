"""Equational research environment (B20: W18–W20, E3).

A *system* is a finite set of equational axioms over a signature, for a variety whose
equational theory Genesis can decide exactly:
  * Boolean algebras: an equation holds in every Boolean algebra iff it holds in the
    two-element one (the variety is generated by it), so truth is evaluation over {0, 1};
  * groups: an equation holds in every group iff both sides reduce to the same word in
    the free group.
The decider is ground truth for labels and for screening false conjectures. It is not a
proof: a lemma enters a library only with an E proof from the system's axioms (and
earlier library lemmas), and is formally checked only after Lean replay of that proof.

Several systems axiomatize the same variety differently (Wolfram's single axiom versus
Sheffer's basis for Boolean algebra in the Sheffer stroke; a single axiom in division
versus the standard basis for groups). Research in one system can therefore be compared
with research in another, and lemmas can be transported where the signature agrees.
"""
from itertools import product
import random

from ..fol import parse, to_tptp

SYSTEMS = {
    'ba_wolfram': {'variety': 'boolean', 'ops': {'s': 2}, 'decider': 'nand',
                   'axioms': ['![X,Y,Z]: s(s(s(X,Y),Z),s(X,s(s(X,Z),X))) = Z']},
    'ba_sheffer': {'variety': 'boolean', 'ops': {'s': 2}, 'decider': 'nand',
                   'axioms': ['![X]: s(s(X,X),s(X,X)) = X', '![X,Y]: s(X,s(Y,s(Y,Y))) = s(X,X)',
                              '![X,Y,Z]: s(s(X,s(Y,Z)),s(X,s(Y,Z))) = s(s(s(Y,Y),X),s(s(Z,Z),X))']},
    'ba_huntington': {'variety': 'boolean', 'ops': {'plus': 2, 'n': 1}, 'decider': 'or_not',
                      'axioms': ['![X,Y]: plus(X,Y) = plus(Y,X)',
                                 '![X,Y,Z]: plus(plus(X,Y),Z) = plus(X,plus(Y,Z))',
                                 '![X,Y]: plus(n(plus(n(X),Y)),n(plus(n(X),n(Y)))) = X']},
    'bool_ring': {'variety': 'boolean ring', 'ops': {'plus': 2, 'times': 2, 'neg': 1, 'zero': 0}, 'decider': 'xor_and',
                  'axioms': ['![X,Y,Z]: plus(plus(X,Y),Z) = plus(X,plus(Y,Z))', '![X,Y]: plus(X,Y) = plus(Y,X)',
                             '![X]: plus(zero,X) = X', '![X]: plus(X,neg(X)) = zero',
                             '![X,Y,Z]: times(times(X,Y),Z) = times(X,times(Y,Z))',
                             '![X,Y,Z]: times(X,plus(Y,Z)) = plus(times(X,Y),times(X,Z))',
                             '![X,Y,Z]: times(plus(X,Y),Z) = plus(times(X,Z),times(Y,Z))', '![X]: times(X,X) = X']},
    'dist_lattice': {'variety': 'distributive lattice', 'ops': {'meet': 2, 'join': 2}, 'decider': 'lattice2',
                     'axioms': ['![X,Y]: meet(X,Y) = meet(Y,X)', '![X,Y]: join(X,Y) = join(Y,X)',
                                '![X,Y,Z]: meet(meet(X,Y),Z) = meet(X,meet(Y,Z))',
                                '![X,Y,Z]: join(join(X,Y),Z) = join(X,join(Y,Z))',
                                '![X,Y]: meet(X,join(X,Y)) = X', '![X,Y]: join(X,meet(X,Y)) = X',
                                '![X,Y,Z]: meet(X,join(Y,Z)) = join(meet(X,Y),meet(X,Z))']},
    'grp_div': {'variety': 'group', 'ops': {'div': 2}, 'decider': 'free_group',
                'axioms': ['![X,Y,Z]: div(X,div(div(div(div(X,X),Y),Z),div(div(div(X,X),X),Z))) = Y']},
    'grp_std': {'variety': 'group', 'ops': {'mul': 2, 'inv': 1, 'e': 0}, 'decider': 'free_group',
                'axioms': ['![X,Y,Z]: mul(mul(X,Y),Z) = mul(X,mul(Y,Z))', '![X]: mul(e,X) = X',
                           '![X]: mul(inv(X),X) = e']},
}
VARS = ('X', 'Y', 'Z')


# ---------------------------------------------------------------- deciders

def _vars(t, out):
    if t[0] == 'var':
        out.add(t[1])
    else:
        for a in t[2]:
            _vars(a, out)
    return out


def _bool(t, env, decider):
    if t[0] == 'var':
        return env[t[1]]
    a = [_bool(x, env, decider) for x in t[2]]
    f = t[1]
    if decider == 'nand' and f == 's':
        return 1 - (a[0] & a[1])
    if decider == 'or_not':
        if f == 'plus':
            return a[0] | a[1]
        if f == 'n':
            return 1 - a[0]
    if decider == 'xor_and':
        return {'plus': lambda: a[0] ^ a[1], 'times': lambda: a[0] & a[1], 'neg': lambda: a[0],
                'zero': lambda: 0}[f]()
    if decider == 'lattice2':
        return {'meet': lambda: a[0] & a[1], 'join': lambda: a[0] | a[1]}[f]()
    raise ValueError(f'symbol {f} outside the {decider} decider')


def _word(t):
    """Free-group word of a term: a reduced list of (variable, ±1)."""
    if t[0] == 'var':
        return [(t[1], 1)]
    f, a = t[1], [_word(x) for x in t[2]]
    if f == 'e':
        w = []
    elif f == 'inv':
        w = [(v, -s) for v, s in reversed(a[0])]
    elif f == 'mul':
        w = a[0] + a[1]
    elif f == 'div':
        w = a[0] + [(v, -s) for v, s in reversed(a[1])]
    else:
        raise ValueError(f'symbol {f} outside the free-group decider')
    out = []
    for x in w:
        if out and out[-1][0] == x[0] and out[-1][1] == -x[1]:
            out.pop()
        else:
            out.append(x)
    return out


# Defined operations (B21, W22): name -> (parameter names, defining term over earlier
# symbols). Deciders evaluate a defined symbol through its definition, so a definitional
# extension is decided exactly like the base variety.
DEFINITIONS = {}


def unfold_definitions(t):
    if t[0] == 'var':
        return t
    args = tuple(unfold_definitions(a) for a in t[2])
    if t[1] in DEFINITIONS:
        params, body = DEFINITIONS[t[1]]
        return unfold_definitions(_subst_vars(body, dict(zip(params, args))))
    return ('fn', t[1], args)


def _subst_vars(t, m):
    if t[0] == 'var':
        return m.get(t[1], t)
    return ('fn', t[1], tuple(_subst_vars(a, m) for a in t[2]))


def register(name, spec):
    """Add a derived system (e.g. a definitional extension) under a new name."""
    if name in SYSTEMS and SYSTEMS[name] != spec:
        raise ValueError(f'system {name} already registered differently')
    SYSTEMS[name] = spec


def fingerprint(t, decider, vars_=VARS):
    """A value equal for two terms iff they denote the same term function in the variety."""
    if DEFINITIONS:
        t = unfold_definitions(t)
    if decider == 'free_group':
        return tuple(_word(t))
    return tuple(_bool(t, dict(zip(vars_, bits)), decider) for bits in product((0, 1), repeat=len(vars_)))


def holds(eq, decider):
    l, r = eq
    vs = tuple(sorted(_vars(l, set()) | _vars(r, set()))) or ('X',)
    return fingerprint(l, decider, vs) == fingerprint(r, decider, vs)


# ---------------------------------------------------------------- terms and equations

def terms(ops, max_size, vars_=VARS):
    """All terms with at most `max_size` operation nodes, by size."""
    by = {0: [('var', v) for v in vars_] + [('fn', f, ()) for f, a in sorted(ops.items()) if a == 0]}
    for k in range(1, max_size + 1):
        acc = []
        for f, a in sorted(ops.items()):
            if a == 1:
                acc += [('fn', f, (x,)) for x in by[k - 1]]
            elif a == 2:
                acc += [('fn', f, (x, y)) for i in range(k) for x in by[i] for y in by[k - 1 - i]]
        by[k] = acc
    return by


def size(t):
    return 0 if t[0] == 'var' or not t[2] else 1 + sum(size(a) for a in t[2])


def canon(eq):
    """Variables renamed by first appearance; the smaller orientation."""
    def ren(t, m):
        if t[0] == 'var':
            m.setdefault(t[1], VARS[len(m)] if len(m) < len(VARS) else f'V{len(m)}')
            return ('var', m[t[1]])
        return ('fn', t[1], tuple(ren(a, m) for a in t[2]))
    l, r = eq
    m1, m2 = {}, {}
    a = (ren(l, m1), ren(r, m1))
    b = (ren(r, m2), ren(l, m2))
    return min(a, b, key=repr)


def closed(eq):
    l, r = eq
    f = ('eq', l, r)
    for v in sorted(_vars(l, set()) | _vars(r, set()), reverse=True):
        f = ('all', v, f)
    return f


def text(eq):
    return to_tptp(closed(eq))


def axioms(system):
    return [parse(a) for a in SYSTEMS[system]['axioms']]


def true_equations(system, max_size, *, per_bucket=6, seed=0):
    """True equations with at most `max_size` nodes in total, deduplicated up to renaming
    and orientation: pairs of terms with the same fingerprint."""
    spec = SYSTEMS[system]
    rng = random.Random(seed)
    by = terms(spec['ops'], max_size)
    buckets = {}
    for k, ts in by.items():
        for t in ts:
            buckets.setdefault(fingerprint(t, spec['decider']), []).append(t)
    out, seen = [], set()
    for fp in sorted(buckets, key=repr):
        ts = sorted(buckets[fp], key=lambda t: (size(t), repr(t)))[:40]      # the smallest members
        pairs = [(a, b) for i, a in enumerate(ts) for b in ts[i + 1:]
                 if size(a) + size(b) <= max_size and not (a[0] == 'var' and b[0] == 'var')]
        rng.shuffle(pairs)
        kept = 0
        for a, b in sorted(pairs[:per_bucket * 4], key=lambda p: (size(p[0]) + size(p[1]), repr(p))):
            c = canon((a, b))
            if c in seen or c[0] == c[1]:
                continue
            seen.add(c); out.append(c); kept += 1
            if kept >= per_bucket:
                break
    return out


def false_equations(system, max_size, count, *, seed=0):
    spec = SYSTEMS[system]
    rng = random.Random(seed)
    by = terms(spec['ops'], max_size)
    flat = [t for k in by for t in by[k]]
    out, seen = [], set()
    while len(out) < count:
        a, b = rng.choice(flat), rng.choice(flat)
        if size(a) + size(b) > max_size or a == b:
            continue
        c = canon((a, b))
        if c in seen or holds(c, spec['decider']):
            continue
        seen.add(c); out.append(c)
    return out


