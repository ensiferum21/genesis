"""Counterfactual theories (U4's training and attack worlds) and sealed judging worlds.

A counterfactual theory changes how functions are defined - recursing on the other
argument, accumulating instead of appending, adding a step - while keeping the signature.
Tasks inside a counterfactual theory are generated by enumeration and testing inside that
theory. Two disjoint mutation families exist: TRAIN mutations (used to fit and attack
preconditions) and SEALED mutations (used only to judge them, INV-19).
"""
from __future__ import annotations

import numpy as np

from .theory import Rule, Theory

TRAIN_MUTATIONS = {
    "plus_second_arg": ("plus", ["plus x Z = x", "plus x (S y) = S (plus x y)"]),
    "mult_right": ("mult", ["mult Z y = Z", "mult (S x) y = plus (mult x y) y"]),
    "len_tail": ("len", ["len Nil = Z", "len (Cons x xs) = plus (len xs) (S Z)"]),
    "sum_right": ("sum", ["sum Nil = Z", "sum (Cons x xs) = plus (sum xs) x"]),
    "double_plus": ("double", ["double Z = Z", "double (S x) = plus (S (S Z)) (double x)"]),
    "incall_plus": ("incall", ["incall Nil = Nil", "incall (Cons x xs) = Cons (plus x (S Z)) (incall xs)"]),
}

SEALED_MUTATIONS = {
    "rev_via_qrev": ("rev", ["rev Nil = Nil", "rev (Cons x xs) = qrev xs (Cons x Nil)"]),
    "plus_swap": ("plus", ["plus Z y = y", "plus (S x) y = plus x (S y)"]),
    "max_via_minus": ("max", ["max Z y = y", "max (S x) Z = S x", "max (S x) (S y) = S (max y x)"]),
    "rot_snoc": ("rot", ["rot Z xs = xs", "rot (S n) Nil = Nil",
                         "rot (S n) (Cons x xs) = rot n (rev (Cons x (rev xs)))"]),
}


def mutate(theory: Theory, name: str, family: dict, origin: str) -> Theory:
    f, eqs = family[name]
    th = theory.copy()
    p = th.parser()
    th.defs[f] = [Rule(("def", f, k), *p.parse_eq(e)) for k, e in enumerate(eqs)]
    th.name = f"{theory.name}+{name}"
    th.origin = origin
    return th


def random_mutant(theory: Theory, rng: np.random.Generator, family: dict, origin: str, k: int = 1) -> Theory:
    names = list(family)
    picks = rng.choice(len(names), size=min(k, len(names)), replace=False)
    th = theory
    for i in picks:
        th = mutate(th, names[int(i)], family, origin)
    return th
